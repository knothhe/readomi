import { afterEach, describe, expect, it, vi } from "vitest"
import { SubtitleTranslationWindow } from "../translation-window"

const cues = Array.from({ length: 100 }, (_, i) => ({ start: i * 2, end: i * 2 + 2, text: `Cue ${i}` }))
async function flush() {
  await Promise.resolve()
  await Promise.resolve()
  await Promise.resolve()
}
afterEach(() => vi.useRealTimers())

describe("subtitle lookahead scheduling", () => {
  it("prepares a rolling window before playback, caches translations and does not submit the whole video", async () => {
    const translate = vi.fn(async text => `Translated ${text}`)
    const window = new SubtitleTranslationWindow(translate)
    window.update(cues, 0, 1, "Cue 0")
    expect(translate.mock.calls.map(c => c[0])).toContain("Cue 7")
    await flush()
    await flush()
    expect(window.get("Cue 2")).toBe("Translated Cue 2")
    expect(translate.mock.calls.map(c => c[0])).not.toContain("Cue 20")
    const count = translate.mock.calls.length
    window.update(cues, 0, 1, "Cue 0")
    expect(translate).toHaveBeenCalledTimes(count)
    window.dispose()
  })
  it("reserves capacity for a seek and fills the new position instead of draining an old FIFO", async () => {
    const resolves = new Map<string, (text: string) => void>()
    const translate = vi.fn((text: string) => new Promise<string>(resolve => resolves.set(text, resolve)))
    const window = new SubtitleTranslationWindow(translate)
    window.update(cues, 0, 1, "Cue 0")
    window.update(cues, 100, 1, "Cue 50")
    expect(translate).toHaveBeenCalledWith("Cue 50")
    resolves.get("Cue 0")!("Old")
    resolves.get("Cue 1")!("Old")
    await flush()
    expect(translate).toHaveBeenCalledWith("Cue 51")
    expect(translate).not.toHaveBeenCalledWith("Cue 8")
    window.dispose()
  })
  it("extends the window for slow models and fast playback", async () => {
    vi.useFakeTimers()
    let resolve!: (text: string) => void
    const translate = vi.fn((text: string) => text === "Cue 0" ? new Promise<string>(r => resolve = r) : Promise.resolve(text))
    const window = new SubtitleTranslationWindow(translate)
    window.update(cues, 0, 2, "Cue 0")
    await vi.advanceTimersByTimeAsync(15000)
    resolve("Translation")
    await flush()
    await flush()
    expect(translate).toHaveBeenCalledWith("Cue 40")
    expect(translate).not.toHaveBeenCalledWith("Cue 61")
    window.dispose()
  })
  it("does not let an old language response populate the new cache or remove its pending request", async () => {
    const resolves: ((text: string) => void)[] = []
    const translate = vi.fn(() => new Promise<string>(r => resolves.push(r)))
    const window = new SubtitleTranslationWindow(translate)
    window.update([], 0, 1, "Hello")
    window.reset()
    window.update([], 0, 1, "Hello")
    resolves[0]("Old language")
    await flush()
    expect(window.get("Hello")).toBeUndefined()
    window.update([], 0, 1, "Hello")
    expect(translate).toHaveBeenCalledTimes(2)
    resolves[1]("New language")
    await flush()
    expect(window.get("Hello")).toBe("New language")
    window.dispose()
  })
  it("keeps a failed cue from retrying every tick but retries after leaving and returning", async () => {
    const translate = vi.fn().mockRejectedValue(new Error("offline"))
    const window = new SubtitleTranslationWindow(translate)
    window.update([], 0, 1, "Hello")
    await flush()
    window.update([], 0, 1, "Hello")
    expect(translate).toHaveBeenCalledTimes(1)
    window.update([], 1, 1, "")
    window.update([], 0, 1, "Hello")
    expect(translate).toHaveBeenCalledTimes(2)
    window.dispose()
  })
  it("retries an old in-flight failure after a service switch while keeping successful captions", async () => {
    let reject!: (error: Error) => void
    const translate = vi.fn()
      .mockResolvedValueOnce("Existing caption")
      .mockImplementationOnce(() => new Promise<string>((_resolve, r) => reject = r))
      .mockResolvedValue("New service caption")
    const window = new SubtitleTranslationWindow(translate)
    window.update([], 0, 1, "Hello")
    await flush()
    window.update([], 1, 1, "Goodbye")
    window.clearFailures()
    window.update([], 1, 1, "Goodbye")
    expect(translate).toHaveBeenCalledTimes(2)

    reject(new Error("Old service went offline"))
    await flush()
    await flush()

    expect(window.get("Hello")).toBe("Existing caption")
    expect(window.get("Goodbye")).toBe("New service caption")
    expect(window.hasFailed("Goodbye")).toBe(false)
    expect(translate).toHaveBeenCalledTimes(3)
    window.dispose()
  })
})
